(function () {
  "use strict";

  const STORAGE_KEY = "remanente_lang";

  function currentLang() {
    return localStorage.getItem(STORAGE_KEY) || "es";
  }

  function t(key) {
    const entry = window.REMANENTE_I18N[key];
    if (!entry) return key;
    return entry[currentLang()] || entry.es;
  }

  function applyLang(lang) {
    document.documentElement.lang = lang;
    localStorage.setItem(STORAGE_KEY, lang);

    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      const entry = window.REMANENTE_I18N[key];
      if (entry) el.innerHTML = entry[lang] || entry.es;
    });

    document.querySelectorAll(".lang-toggle__btn").forEach((btn) => {
      btn.classList.toggle("is-active", btn.dataset.lang === lang);
    });

    document.dispatchEvent(new CustomEvent("remanente:langchange", { detail: { lang } }));
  }

  function init() {
    applyLang(currentLang());
    document.querySelectorAll(".lang-toggle__btn").forEach((btn) => {
      btn.addEventListener("click", () => applyLang(btn.dataset.lang));
    });
  }

  window.REMANENTE_I18N.t = t;
  window.REMANENTE_I18N.applyLang = applyLang;
  window.REMANENTE_I18N.currentLang = currentLang;

  document.addEventListener("DOMContentLoaded", init);
})();
